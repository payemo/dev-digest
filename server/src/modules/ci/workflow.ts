import YAML from 'yaml';
import type { CiPostAs, CiTrigger } from '@devdigest/shared';
import {
  CI_ARTIFACT_NAME,
  CI_NODE_VERSION,
  CI_RESULT_FILE,
  CI_RUNNER_PATH,
  CI_WORKFLOW_MAX_CHARS,
  CI_WORKFLOW_TEMPLATE_VERSION,
} from './constants.js';
import { CI_SLUG_RE } from './helpers.js';
import { ValidationError } from '../../platform/errors.js';

export interface WorkflowInput {
  agentName: string;
  agentSlug: string;
  triggers: CiTrigger[];
  postAs: CiPostAs;
}

/** The exact command the workflow must run for `slug`. */
export function runnerInvocation(agentSlug: string): string {
  return `node ${CI_RUNNER_PATH} review --agent ${agentSlug}`;
}

/** Canonical trigger order, so the same selection always yields the same file. */
const TRIGGER_ORDER: CiTrigger[] = ['opened', 'synchronize', 'reopened'];

/**
 * Generate `.github/workflows/devdigest-review-<slug>.yml`.
 *
 * Least privilege: `contents: read` + `pull-requests: write` only; checkout
 * without persisted credentials; fork PRs are skipped (they get no secrets and
 * the studio would reject their runs anyway). The only secrets referenced are
 * `OPENROUTER_API_KEY` and the automatic `GITHUB_TOKEN`. The result artifact is
 * uploaded even when the review step fails, so a blocking verdict is still
 * ingested.
 */
export function buildWorkflowYaml(input: WorkflowInput): string {
  if (!CI_SLUG_RE.test(input.agentSlug)) {
    throw new ValidationError(`invalid agent slug: ${input.agentSlug}`);
  }
  const types = TRIGGER_ORDER.filter((t) => input.triggers.includes(t));
  // JSON string literals are valid YAML double-quoted scalars, which keeps an
  // arbitrary agent name from breaking out of the `name:` value.
  const name = JSON.stringify(`DevDigest review — ${input.agentName}`);
  return `# Generated by DevDigest (workflow template v${CI_WORKFLOW_TEMPLATE_VERSION}).
# Runs the bundled DevDigest agent-runner on pull requests and uploads the
# result as the "${CI_ARTIFACT_NAME}" artifact, which the studio ingests.
# Requires the repository secret OPENROUTER_API_KEY.
name: ${name}

on:
  pull_request:
    types: [${types.join(', ')}]

permissions:
  contents: read
  pull-requests: write

jobs:
  review:
    # Fork PRs get no secrets and are never ingested — skip them.
    if: github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v4
        with:
          persist-credentials: false
      - uses: actions/setup-node@v4
        with:
          node-version: '${CI_NODE_VERSION}'
      - name: Run DevDigest review
        run: ${runnerInvocation(input.agentSlug)}
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
          DEVDIGEST_POST_AS: ${input.postAs}
      - name: Upload DevDigest result
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: ${CI_ARTIFACT_NAME}
          path: ${CI_RESULT_FILE}
          if-no-files-found: ignore
          retention-days: 14
`;
}

/** True when some job still has an `upload-artifact` step named `CI_ARTIFACT_NAME`. */
function hasResultUpload(doc: object): boolean {
  const jobs = (doc as { jobs?: unknown }).jobs;
  if (jobs == null || typeof jobs !== 'object') return false;
  return Object.values(jobs).some((job) => {
    const steps = (job as { steps?: unknown } | null)?.steps;
    return (
      Array.isArray(steps) &&
      steps.some((step) => {
        const s = step as { uses?: unknown; with?: { name?: unknown } | null } | null;
        return (
          typeof s?.uses === 'string' &&
          s.uses.startsWith('actions/upload-artifact') &&
          s.with?.name === CI_ARTIFACT_NAME
        );
      })
    );
  });
}

export interface WorkflowValidation {
  errors: string[];
  warnings: string[];
}

/**
 * Check a user-edited workflow. Errors block the export; warnings are shown
 * but allowed (e.g. removing the upload step only disables ingest).
 */
export function validateWorkflowYaml(text: string, agentSlug: string): WorkflowValidation {
  const errors: string[] = [];
  const warnings: string[] = [];
  if (text.length > CI_WORKFLOW_MAX_CHARS) {
    errors.push(`workflow is longer than ${CI_WORKFLOW_MAX_CHARS} characters`);
    return { errors, warnings };
  }
  let parsed: unknown;
  try {
    parsed = YAML.parse(text);
  } catch (err) {
    errors.push(`workflow is not valid YAML: ${(err as Error).message}`);
    return { errors, warnings };
  }
  if (parsed == null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    errors.push('workflow must be a YAML mapping');
    return { errors, warnings };
  }
  if (!text.includes(runnerInvocation(agentSlug))) {
    errors.push(`workflow must still run "${runnerInvocation(agentSlug)}"`);
  }
  // Look at the parsed steps, not the text: the generated header comment also
  // names the artifact, so a substring match survives deleting the upload step.
  if (!hasResultUpload(parsed)) {
    warnings.push(
      `the "${CI_ARTIFACT_NAME}" upload step was removed — CI runs will not appear in the studio`,
    );
  }
  return { errors, warnings };
}
