import YAML from 'yaml';
import { AgentManifest, type CiFailOn, type Provider } from '@devdigest/shared';
import { ValidationError } from '../../platform/errors.js';

/** The agent fields the exported manifest is built from. */
export interface ManifestAgent {
  name: string;
  version: number;
  provider: Provider;
  model: string;
  systemPrompt: string;
  strategy: 'auto' | 'single-pass' | 'map-reduce';
  ciFailOn: CiFailOn;
}

/**
 * Build `.devdigest/agents/<slug>.yaml`. The object goes through
 * `AgentManifest.parse` — the SAME schema the agent-runner validates with —
 * and the emitted text is round-tripped through `YAML.parse` + the schema
 * again, so a manifest the runner would reject can never be exported.
 */
export function buildManifestYaml(agent: ManifestAgent, skillSlugs: string[]): string {
  const manifest = AgentManifest.parse({
    name: agent.name,
    version: agent.version,
    provider: agent.provider,
    model: agent.model,
    system_prompt: agent.systemPrompt,
    skills: skillSlugs,
    strategy: agent.strategy,
    ci_fail_on: agent.ciFailOn,
  });
  const body = YAML.stringify(manifest, { lineWidth: 0 });
  const text = `# generated by DevDigest — agent v${agent.version}\n${body}`;

  const roundTrip = AgentManifest.safeParse(YAML.parse(text));
  if (!roundTrip.success || JSON.stringify(roundTrip.data) !== JSON.stringify(manifest)) {
    throw new ValidationError('generated agent manifest does not round-trip through AgentManifest');
  }
  return text;
}
